    #[test]
    fn syncing_creates_a_missing_copy_and_never_overwrites_an_edited_one() {
        let (temp, track, step, project) = fixture("spec-sync");
        let synced = sync(temp.path(), &track, &step, &project, false).unwrap();
        assert_eq!(synced.first().unwrap().action, SyncAction::Created);
        assert!(
            check_learner(temp.path(), &track, &step, &project)
                .unwrap()
                .is_clean()
        );

        std::fs::write(project.join("tests/spec_spec.rs"), "//! mine\n").unwrap();
        let kept = sync(temp.path(), &track, &step, &project, false).unwrap();
        assert_eq!(kept.first().unwrap().action, SyncAction::Kept);
        assert_eq!(
            std::fs::read_to_string(project.join("tests/spec_spec.rs")).unwrap(),
            "//! mine\n"
        );
        let report = check_learner(temp.path(), &track, &step, &project).unwrap();
        assert_eq!(
            report.problems.first().unwrap().kind,
            ProblemKind::LearnerModified
        );
        let fix = &report.problems.first().unwrap().fix;
        assert!(
            fix.contains("kiln spec restore mailer/1.1-workspace"),
            "{fix}"
        );

        let restored = sync(temp.path(), &track, &step, &project, true).unwrap();
        assert_eq!(restored.first().unwrap().action, SyncAction::Restored);
        assert!(
            check_learner(temp.path(), &track, &step, &project)
                .unwrap()
                .is_clean()
        );
    }

