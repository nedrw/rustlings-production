-- The trail: one row per settle, and the constraint that makes an append idempotent.
--
-- Step `jobq/3.6-transaction-isolation`. This is the project's second migration, so it is
-- `0002` (`0001` wrote `jobs`; `mailer` and `relay` number their own files).
--
-- The file is yours to write. What it has to hold is one line of `src/engine/events.rs` per row:
-- `id` (this line's own identity), `job_id` (the job it is about), `kind` (`completed`,
-- `attempt-failed`, `reclaimed`), `attempt` (the row's own count, as the settle saw it), `detail`
-- (the reason, when there is one) and `at` (the instant the caller stamped it with).
--
-- Two things about the file are decisions rather than transcription:
-- 1. a line's identity is `(job_id, kind, attempt)` — the same settle appended twice has to be the
--    same line, and that promise is one the *database* keeps, not one an application checks first;
-- 2. an operator reads one job's trail, and later steps read all of them (`jobq/3.16-dlq-tooling`
--    lists what died, `jobq/3.17-error-budget-alerts` counts by kind), so which index that needs is
--    worth one thought before the table is written.
