-- The lease: who holds a job, and until when.
--
-- Step `jobq/3.7-leases-and-recovery`. This is the project's third migration, so it is `0003`.
--
-- The file is yours to write. Two columns go onto `jobs`:
--
--   * `lease_owner` — who holds the row, as the name the worker calls itself (the same string the
--     port already takes in every settle, and the one an operator greps for);
--   * `lease_expires_at` — the instant after which the row is presumed abandoned.
--
-- Both are `null` when nobody holds the job, and a claimed row carries both. Two things about this
-- file are decisions rather than transcription:
--
-- 1. **the reclaimer's predicate is `state = 'running'` and `lease_expires_at` past.** That is the
--    query a worker runs when it starts, and every turn after — the cost of recovering from a crash
--    grows with the table unless an index covers exactly it;
-- 2. **the settle's guard widens.** A settle already refuses a job that is not running; from this
--    step on it also refuses one whose lease somebody else holds, which is what stops a worker that
--    was already declared dead (`kill -9` and a lease that ran out) from settling the attempt the
--    *next* worker is running right now. That check is on `lease_owner`, so this is the column it
--    reads.
